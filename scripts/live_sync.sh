#!/usr/bin/env bash
# Publish a live snapshot of the running experiments to GitHub every 15 minutes.
#
# Training writes its epoch log locally; this loop turns the newest log line of
# every active run into results/LIVE.md, refreshes the summary table and pushes.
# Pushes are serialised with flock so they never race with run_and_sync.sh.
set -uo pipefail
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"
export PYTHONPATH="$REPO_ROOT:${PYTHONPATH:-}"
INTERVAL="${INTERVAL:-900}"

snapshot() {
  python3 - <<'PY'
import json, re, subprocess
from pathlib import Path

rows = []
logs = sorted(Path("logs").glob("*.log"), key=lambda p: p.stat().st_mtime, reverse=True)
for log in logs[:4]:
    text = log.read_text(errors="ignore").replace("\r", "\n")
    epochs = re.findall(r"epoch (\d+) mIoU ([\d.]+)", text)
    cur = re.findall(r"ep (\d+)/(\d+)", text)
    if not cur:
        continue
    ep, total = cur[-1]
    best = max(epochs, key=lambda x: float(x[1])) if epochs else ("-", "-")
    rows.append((log.stem, f"{ep}/{total}", best[1], best[0], epochs[-1][1] if epochs else "-"))

out = ["# Live status", "", f"<!-- generated by scripts/live_sync.sh -->", "",
       "| run | epoch | best mIoU | best ep | last mIoU |", "|---|---|---|---|---|"]
for r in rows:
    out.append(f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} | {r[4]} |")

done = []
for path in sorted(Path("results").glob("*/metrics.json")):
    try:
        m = json.loads(path.read_text())
    except Exception:
        continue
    done.append((m.get("experiment", path.parent.name), m.get("best_miou", 0.0),
                 m.get("mAcc", float("nan"))))
out += ["", "## finished runs", "", "| run | best mIoU | mAcc |", "|---|---|---|"]
for name, miou, macc in sorted(done, key=lambda x: -x[1]):
    out.append(f"| {name} | {miou:.2f} | {macc:.2f} |")
Path("results/LIVE.md").write_text("\n".join(out) + "\n")
print("\n".join(out[:12]))
PY

  python3 scripts/summarize.py >/dev/null 2>&1 || true
  bash scripts/sync_results.sh "live update" || true
}

while true; do
  flock -w 600 /tmp/cvpr_sync.lock bash -c "$(declare -f snapshot); cd '$REPO_ROOT'; export PATH=\"$PATH\"; snapshot"
  sleep "$INTERVAL"
done
